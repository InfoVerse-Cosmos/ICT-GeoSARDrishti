import { useEffect, useState } from "react";
import { api } from "@/api/client.js";
import { REGIME_LEGEND, useMissionStore } from "@/store/useMissionStore.js";

// Tab 1 — Scene & Validation metrics (SRS §4.2.4): area per class, valid pixel %,
// OPERA DSWx inter-sensor agreement, JRC anomaly breakdown, regimes, season summary.
export default function ScenePanel() {
  const { activeAoiId, timeline, activeDate, timelineMeta, connection } = useMissionStore();
  const [prov, setProv] = useState(null);

  useEffect(() => {
    if (connection === "OFFLINE" || connection === "CONNECTING") return;
    (async () => {
      const res = await api.provenance(activeAoiId);
      setProv(res.data || null);
    })();
  }, [activeAoiId, connection]);

  const entry = timeline.find((t) => t.date === activeDate);
  const m = entry?.metrics;
  const season = timelineMeta.season_summary;

  return (
    <div className="space-y-4 text-xs">
      {timelineMeta.synthetic_test_data && (
        <div className="rounded border border-alert/60 bg-alert/10 p-2 telemetry-mono text-alert">
          SYNTHETIC TEST DATA — pipeline test pack, not a NISAR observation.
        </div>
      )}

      <Section title={`Scene · ${activeDate || "—"}`}>
        {!m ? (
          <p className="telemetry-mono text-slate-400">
            {timeline.length === 0
              ? "No acquisitions loaded."
              : "Per-date metrics are generated by scripts/02 (data pack pending)."}
          </p>
        ) : (
          <div className="grid grid-cols-2 gap-2">
            <Metric label="Open water" value={m.open_water_km2} unit="km²" colour="text-sky-300" />
            <Metric label="Flooded vegetation" value={m.flooded_veg_km2} unit="km²" colour="text-emerald-300" />
            <Metric label="· natural" value={m.natural_flooded_veg_km2} unit="km²" colour="text-emerald-300" />
            <Metric label="· paddy-like" value={m.paddy_like_km2} unit="km²" colour="text-paddy" />
            <Metric label="Dry / other" value={m.dry_km2} unit="km²" colour="text-slate-300" />
            <Metric label="Valid pixels" value={m.valid_pixel_pct} unit="%" />
            <Metric label="AOI coverage" value={m.aoi_coverage_pct} unit="%" />
            <Metric label="Otsu τ HH" value={m.otsu_hh_db} unit="dB" />
            <Metric label="τ HV" value={m.otsu_hv_db ?? "n/a"} unit={m.otsu_hv_db != null ? "dB" : ""} />
            {m.dswx_agreement_pct != null && (
              <Metric label="OPERA DSWx agreement" value={m.dswx_agreement_pct} unit="%" colour="text-cyan" />
            )}
            {m.is_reference && <p className="col-span-2 text-slate-400">Dry post-monsoon reference scene (ΔHH baseline).</p>}
          </div>
        )}
      </Section>

      <Section title="Season / stack">
        <div className="grid grid-cols-2 gap-2">
          <Metric label="Same-track dates" value={timeline.length} />
          <Metric label="Fallback plan" value={timelineMeta.fallback_plan || "—"} />
          <Metric label="Track / frame" value={timelineMeta.track_frame || "—"} />
          <Metric label="Mode" value={timelineMeta.single_pol_mode ? "Single-Pol HH" : "Dual-Pol HH+HV"} />
          {season && (
            <>
              <Metric label="Ever wet" value={season.ever_wet_km2} unit="km²" />
              <Metric label="Wet every obs." value={season.wet_every_observation_km2} unit="km²" />
            </>
          )}
        </div>
      </Section>

      <Section title="Validation">
        <ul className="space-y-1 text-slate-300">
          <li>
            OPERA DSWx:{" "}
            <span className="telemetry-mono text-cyan">
              {prov?.opera_dswx_agreement_pct != null ? `${prov.opera_dswx_agreement_pct}%` : "—"}
            </span>{" "}
            <span className="text-slate-400">inter-sensor agreement, not ground-truth accuracy</span>
            {prov?.opera_dswx && (
              <span className="block telemetry-mono text-xs text-slate-400">
                DSWx {prov.opera_dswx.dswx_date} vs NISAR {prov.opera_dswx.nisar_date} ·{" "}
                {prov.opera_dswx.compared_pixels} px · IoU {prov.opera_dswx.open_water_iou_pct ?? "—"}%
              </span>
            )}
          </li>
          <li>
            JRC unusual open water:{" "}
            <span className="telemetry-mono text-alert">
              {prov?.jrc ? `${prov.jrc.unusual_open_water_km2} km² (${prov.jrc.unusual_share_pct}%)` : "—"}
            </span>{" "}
            <span className="text-slate-400">occurrence &lt; 20%, open-water class only</span>
          </li>
          <li>
            ΔHH double-bounce threshold:{" "}
            <span className="telemetry-mono">
              {prov?.delta_hh_params
                ? `≥ ${prov.delta_hh_params.min_delta_hh_db} dB (ΔRatio ≥ ${prov.delta_hh_params.min_delta_ratio_db} dB)`
                : "≥ 3.0 dB"}
            </span>
          </li>
          {prov?.calibration_check && (
            <li>
              Calibration {prov.calibration_check.provisional_date} → {prov.calibration_check.validated_date}:{" "}
              <span className="telemetry-mono">
                {prov.calibration_check.median_offset_db > 0 ? "+" : ""}
                {prov.calibration_check.median_offset_db} dB ({prov.calibration_check.channel})
              </span>
            </li>
          )}
        </ul>
      </Section>

      {prov?.limitations?.length > 0 && (
        <Section title="Limitations">
          <ul className="list-disc space-y-1 pl-4 text-xs text-slate-400">
            {prov.limitations.map((l, i) => (
              <li key={i}>{l}</li>
            ))}
          </ul>
        </Section>
      )}

      {prov?.gmm?.regime_area_km2 && (
        <Section title="GMM hydrological regimes (unsupervised)">
          <ul className="space-y-1">
            {REGIME_LEGEND.map(([name, colour]) => (
              <li key={name} className="flex items-center gap-2">
                <span className="h-3 w-3 rounded-sm" style={{ backgroundColor: colour }} />
                <span className="flex-1 text-slate-300">{name}</span>
                <span className="telemetry-mono">{prov.gmm.regime_area_km2[name] ?? 0} km²</span>
              </li>
            ))}
          </ul>
        </Section>
      )}
    </div>
  );
}

function Section({ title, children }) {
  return (
    <section>
      <h3 className="mb-1 telemetry-mono text-xs uppercase tracking-wide text-cyan">{title}</h3>
      {children}
    </section>
  );
}

function Metric({ label, value, unit = "", colour = "text-slate-100" }) {
  return (
    <div className="rounded border border-grid bg-orbital px-2 py-1">
      <div className="text-xs text-slate-400">{label}</div>
      <div className={`telemetry-mono ${colour}`}>
        {value ?? "—"} {value != null && unit}
      </div>
    </div>
  );
}
